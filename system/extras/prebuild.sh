#!/bin/bash

BUILD_PATH="$1"
BUILD_SOURCE_PATH="$2"
BOARD_PLATFORM_PATH="$3"

# Every sketch must declare its version. The upload tool refuses to flash a
# board with firmware older than what it already runs, and it needs a version
# to compare against.
#
# Deliberately a loose check: it looks for the word, it does not parse the
# value. The linker is what actually enforces this -- the core declares
# openplc_app_version without defining it -- so a false pass here is caught a
# few seconds later, while a false fail would block a correct sketch.
if ! grep -l "OPENPLC_APP_VERSION" "$BUILD_SOURCE_PATH"/*.ino >/dev/null 2>&1; then
  echo "" >&2
  echo "error: this sketch has no version number." >&2
  echo "" >&2
  echo "  Add this line near the top of your sketch:" >&2
  echo "" >&2
  echo "      OPENPLC_APP_VERSION(1, 0, 0);" >&2
  echo "" >&2
  echo "  Without it the board cannot tell whether an upload is newer or" >&2
  echo "  older than the firmware it is already running." >&2
  echo "" >&2
  exit 1
fi

# Create sketch dir if not exists
if [ ! -f "$BUILD_PATH/sketch" ]; then
  mkdir -p "$BUILD_PATH/sketch"
fi

# Create empty build.opt if build_opt.h does not exists in the original sketch dir
# Then add or append -fmacro-prefix-map option to change __FILE__ absolute path of
# the board platform folder to a relative path by using '.'.
# (i.e. the folder containing boards.txt)
if [ ! -f "$BUILD_SOURCE_PATH/build_opt.h" ]; then
  printf '\n-fmacro-prefix-map="%s"=.' "${BOARD_PLATFORM_PATH//\\/\\\\}" > "$BUILD_PATH/sketch/build.opt"
else
  # Else copy the build_opt.h as build.opt
  # Workaround to the header file preprocessing done by arduino-cli
  # See https://github.com/arduino/arduino-cli/issues/1338
  cp "$BUILD_SOURCE_PATH/build_opt.h" "$BUILD_PATH/sketch/build.opt"
  printf '\n-fmacro-prefix-map="%s"=.' "${BOARD_PLATFORM_PATH//\\/\\\\}" >> "$BUILD_PATH/sketch/build.opt"
fi

# KNX role: the sketch writes OPENPLC_KNX_ROLE(TP_DEVICE); or
# OPENPLC_KNX_ROLE(IP_ROUTER); on a line of its own. The generated header is
# force-included into every unit through build.opt, so the KNX stack's own
# files see the same MASK_VERSION. Without a role it defines no MASK_VERSION
# and OpenPLC_KNX stops with #error. $PROD/docs/modules/M3-app-runtime.md R3-24
KNX_ROLE=$(sed -n 's/^[[:space:]]*OPENPLC_KNX_ROLE[[:space:]]*([[:space:]]*\([A-Za-z0-9_]*\)[[:space:]]*).*/\1/p' "$BUILD_SOURCE_PATH"/*.ino 2>/dev/null | sort -u)
case "$KNX_ROLE" in
  "")        KNX_ROLE_DEFS="" ;;
  TP_DEVICE) KNX_ROLE_DEFS="#define MASK_VERSION 0x07B0" ;;
  IP_ROUTER) KNX_ROLE_DEFS="#define MASK_VERSION 0x091A" ;;
  *)
    echo "" >&2
    echo "error: OPENPLC_KNX_ROLE() must be written once, as TP_DEVICE or IP_ROUTER." >&2
    echo "  Found: $(echo $KNX_ROLE)" >&2
    echo "" >&2
    exit 1
    ;;
esac
if [ -n "$KNX_ROLE_DEFS" ]; then
  KNX_ROLE_DEFS="$KNX_ROLE_DEFS
#define KNX_FLASH_SIZE 16384
#define OPENPLC_KNX_ROLE(role) static_assert(OPENPLC_KNX_ROLE_##role == MASK_VERSION, \"OPENPLC_KNX_ROLE() here differs from the one in the .ino file\")"
else
  KNX_ROLE_DEFS="#define OPENPLC_KNX_ROLE(role) static_assert(OPENPLC_KNX_ROLE_##role == 0, \"OPENPLC_KNX_ROLE() must be on a line of its own in the .ino file\")"
fi
KNX_ROLE_H="$BUILD_PATH/sketch/openplc_knx_role.h"
cat > "$KNX_ROLE_H.tmp" <<EOH
/* Generated by prebuild.sh from the sketch's OPENPLC_KNX_ROLE() line. */
#ifndef OPENPLC_KNX_ROLE_H_
#define OPENPLC_KNX_ROLE_H_
#define OPENPLC_KNX_ROLE_TP_DEVICE 0x07B0
#define OPENPLC_KNX_ROLE_IP_ROUTER 0x091A
$KNX_ROLE_DEFS
#endif
EOH
# Replace only on change: a fresh mtime recompiles every unit.
if cmp -s "$KNX_ROLE_H.tmp" "$KNX_ROLE_H"; then
  rm -f "$KNX_ROLE_H.tmp"
else
  mv -f "$KNX_ROLE_H.tmp" "$KNX_ROLE_H"
fi
printf '\n-include "%s"' "$(printf '%s' "$KNX_ROLE_H" | sed 's/\\/\\\\/g')" >> "$BUILD_PATH/sketch/build.opt"

# Force include of SrcWrapper, OpenPLC_Net, OpenPLC_IAP and LwIP to ensure
# library linking. main.cpp calls into OpenPLC_Net and OpenPLC_IAP through the
# core's own stm32/openplc_net.h, which the dependency scanner does not follow,
# so these force-includes are the only thing that compiles those libraries
# into the build at all. Removing this line breaks every sketch's link step.
# Replace the file only when its content changes: a fresh mtime makes
# arduino-cli recompile it and rescan libraries on every build.
cat > "$BUILD_PATH/sketch/SrcWrapper.cpp.tmp" <<'EOC'
#include <SrcWrapper.h>
#include <OpenPLC_Net_Autostart.h>
#include <OpenPLC_IAP_Autostart.h>
EOC
if cmp -s "$BUILD_PATH/sketch/SrcWrapper.cpp.tmp" "$BUILD_PATH/sketch/SrcWrapper.cpp"; then
  rm -f "$BUILD_PATH/sketch/SrcWrapper.cpp.tmp"
else
  mv -f "$BUILD_PATH/sketch/SrcWrapper.cpp.tmp" "$BUILD_PATH/sketch/SrcWrapper.cpp"
fi
